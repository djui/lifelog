import Foundation

/// `_index.md`: the last complete read per source, a "Health" section for the warnings the run passes in (phase 6),
/// and links to this month, every Timeline and Disappeared month, and every WhatsApp chat. Rendered on every run.
enum IndexView {
    static let path = "_index.md"

    static func page(_ context: ViewContext, paths: Set<String>) -> Page {
        Page(path: path, group: "index", keys: [], always: true) { render(context, paths: paths) }
    }

    static func render(_ context: ViewContext, paths: Set<String>) -> String {
        let records = context.records
        func moment(_ record: RunRecord) -> String {
            let offset = (record.timeZone.flatMap(TimeZone.init(identifier:)) ?? context.timeZone).secondsFromGMT(for: record.end)
            return Partition.day(record.end, utcOffset: offset) + " " + Partition.clock(record.end, utcOffset: offset)
        }
        let complete = RunLog.lastComplete(records)
        var latest: [ArchiveSource: RunRecord] = [:]
        for record in records where record.end >= (latest[record.source]?.end ?? .distantPast) { latest[record.source] = record }
        var lines = ["# Archive", "",
                     "Updated \(context.moment(context.now)). The ledger in `\(Ledger.folderName)/` is the source of truth; "
                     + "these pages are views of it, rewritten when their items change and regenerated by `rebuild`.", ""]
        if context.demo { lines += ["**Demo: synthetic examples only.**", ""] }
        lines += ["| Source | Last complete read | Mode | Items | Gone | Pending |", "|---|---|---|---:|---:|---:|"]
        for source in ArchiveSource.allCases where latest[source] != nil || !context.items(source).isEmpty {
            let all = context.items(source)
            let gone = all.filter { $0.state.isTombstone || $0.state == .revoked }.count
            let pending = all.filter { $0.missingSince != nil }.count
            let last = complete[source]
            lines.append("| \(source.displayName) | \(last.map(moment) ?? "never") | \(last?.mode ?? "–") | \(all.count) | \(gone) | \(pending) |")
        }

        // Phase 6 computes these from the run log (capture gaps, WhatsApp Desktop not running, repeated failures).
        lines += ["", "## Health", ""]
        lines += context.health.isEmpty ? ["No warnings."] : context.health.map { "- \(MarkdownWriter.line($0))" }

        let problems = latest.values.filter { !$0.complete }.sorted { $0.source.rawValue < $1.source.rawValue }
        if !problems.isEmpty {
            lines += ["", "## Last read incomplete", ""]
            for record in problems { lines.append("- \(record.source.displayName), \(moment(record)): \(MarkdownWriter.line(record.warnings.first ?? "partial read"))") }
        }

        let month = String(context.day(context.now).prefix(7))
        let current = [("Timeline", "\(TimelineView.folder)/\(month.prefix(4))/\(month).md"), ("Disappeared", "\(DisappearedView.folder)/\(month.prefix(4))/\(month).md"),
                       ("Calendar", "\(CalendarView.folder)/\(month.prefix(4))/\(month).md"), ("Reminders done", "\(RemindersView.folder)/\(month.prefix(4))/\(month).md"),
                       ("Open reminders", RemindersView.openPath)].filter { paths.contains($0.1) }
        if !current.isEmpty {
            lines += ["", "## This month (\(month))", ""] + current.map { "- [\($0.0)](\(ArchivePages.link($0.1, from: path)))" }
        }
        for (title, folder) in [("Timeline", TimelineView.folder), ("Disappeared", DisappearedView.folder)] {
            let months = paths.filter { $0.hasPrefix(folder + "/") }.sorted(by: >)
            guard !months.isEmpty else { continue }
            lines += ["", "## \(title)", ""]
            for (year, pages) in Dictionary(grouping: months, by: { $0.split(separator: "/")[1] }).sorted(by: { $0.key > $1.key }) {
                let links = pages.map { page in "[\(page.split(separator: "/").last!.dropFirst(5).dropLast(3))](\(ArchivePages.link(page, from: path)))" }
                lines.append("- \(year): " + links.joined(separator: " · "))
            }
        }
        let chats = context.chatFolders.sorted { ((context.chatTitles[$0.key] ?? "").lowercased(), $0.key) < ((context.chatTitles[$1.key] ?? "").lowercased(), $1.key) }
        if !chats.isEmpty {
            let counts = Dictionary(grouping: context.items(.whatsapp)) { WhatsAppView.message($0)?.chatJID ?? "" }.mapValues(\.count)
            lines += ["", "## WhatsApp chats", ""]
            for (jid, folder) in chats {
                lines.append("- [\(ArchivePages.label(context.chatTitles[jid] ?? jid))](\(ArchivePages.link("\(folder)/_chat.md", from: path))) · \(counts[jid] ?? 0) messages")
            }
        }
        return lines.joined(separator: "\n") + "\n"
    }
}
